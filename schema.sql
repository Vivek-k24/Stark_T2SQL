CREATE TABLE public.leave_balances (
    leave_balance_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    employee_id INTEGER NOT NULL,
    leave_type TEXT NOT NULL,
    as_of_date DATE NOT NULL,
    balance_hours NUMERIC(10,2) NOT NULL,
    CONSTRAINT leave_balances_pk PRIMARY KEY (leave_balance_id),
    CONSTRAINT leave_balances_id_positive CHECK (leave_balance_id > 0),
    CONSTRAINT leave_balances_snapshot_unique
        UNIQUE (employee_id, leave_type, as_of_date),
    CONSTRAINT leave_balances_type_nonblank CHECK (btrim(leave_type) <> ''),
    CONSTRAINT leave_balances_hours_finite CHECK (balance_hours <> 'NaN'::NUMERIC),
    CONSTRAINT leave_balances_employee_fk FOREIGN KEY (employee_id)
        REFERENCES public.employees (employee_id)
        ON UPDATE NO ACTION ON DELETE RESTRICT
    -- Assumed grain: dated employee/leave-type snapshot, hours (not money).
    -- Negative balances are permitted; selecting the correct snapshot is
    -- future governed temporal behavior, never a wall-clock default.
);

CREATE TABLE public.hr_bp_assignments (
    hr_bp_assignment_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    employee_id INTEGER NOT NULL,
    division_id INTEGER NOT NULL,
    effective_from DATE NOT NULL,
    effective_to DATE,
    CONSTRAINT hr_bp_assignments_pk PRIMARY KEY (hr_bp_assignment_id),
    CONSTRAINT hr_bp_assignments_id_positive CHECK (hr_bp_assignment_id > 0),
    CONSTRAINT hr_bp_assignments_start_unique
        UNIQUE (employee_id, division_id, effective_from),
    CONSTRAINT hr_bp_assignments_employee_fk FOREIGN KEY (employee_id)
        REFERENCES public.employees (employee_id)
        ON UPDATE NO ACTION ON DELETE RESTRICT,
    CONSTRAINT hr_bp_assignments_division_fk FOREIGN KEY (division_id)
        REFERENCES public.divisions (division_id)
        ON UPDATE NO ACTION ON DELETE RESTRICT,
    CONSTRAINT hr_bp_assignments_date_order
        CHECK (effective_to IS NULL OR effective_to > effective_from)
    -- employee_id is the assigned principal. This table has no direct
    -- business-role access grant here; future policy owns function access.
);

-- Lookup indexes complement the primary/unique indexes above. Composite
-- unique indexes already cover department->division, result->run, line->
-- result and leave->employee lookups; no duplicate indexes are needed there.
CREATE INDEX employees_department_idx ON public.employees (department_id);
CREATE INDEX employees_position_idx ON public.employees (position_id);
CREATE INDEX employees_location_idx ON public.employees (location_id);
CREATE INDEX employees_manager_idx ON public.employees (manager_id);
CREATE INDEX employees_hire_date_idx ON public.employees (hire_date);
CREATE INDEX employees_termination_date_idx ON public.employees (termination_date)
    WHERE termination_date IS NOT NULL;

CREATE UNIQUE INDEX employee_compensation_open_unique
    ON public.employee_compensation (employee_id)
    WHERE effective_to IS NULL;

CREATE INDEX payroll_runs_pay_date_idx ON public.payroll_runs (pay_date);
CREATE INDEX payroll_runs_period_end_idx ON public.payroll_runs (pay_period_end);
CREATE INDEX payroll_runs_status_idx ON public.payroll_runs (status);
CREATE INDEX payroll_runs_creator_idx ON public.payroll_runs (created_by_employee_id);
CREATE INDEX payroll_runs_approver_idx ON public.payroll_runs (approved_by_employee_id)
    WHERE approved_by_employee_id IS NOT NULL;
CREATE INDEX payroll_results_employee_idx
    ON public.payroll_results (employee_id, payroll_run_id);
CREATE INDEX payroll_earnings_type_idx ON public.payroll_earnings (earning_type);
CREATE INDEX payroll_deductions_type_idx ON public.payroll_deductions (deduction_type);
CREATE INDEX leave_balances_as_of_idx ON public.leave_balances (as_of_date);

CREATE UNIQUE INDEX hr_bp_assignments_open_unique
    ON public.hr_bp_assignments (employee_id, division_id)
    WHERE effective_to IS NULL;
CREATE INDEX hr_bp_assignments_division_idx
    ON public.hr_bp_assignments (division_id, employee_id);
