-- STARK-TTSQL-FRD-1.8: PostgreSQL 16 schema source, Prompt 1 only.
-- Applying this file is a separate, explicitly authorized future task.
-- It defines exactly the twelve DR-1 tables and no fixture rows or policies.
--
-- Physical-design assumptions: no historical authoritative schema.sql or
-- fixture-generator DDL was supplied. The FRD specifies tables, required
-- employee columns and relationships, but not every physical column/type.
-- This draft therefore uses positive integer identity keys, descriptive
-- reference names/codes, one payroll result per employee/run, and named
-- earning/deduction lines. These choices require reconciliation with any
-- subsequently supplied authoritative generator/dump before fixture loading.
-- Reference names, status/type vocabularies, principals and planted facts
-- are inputs to later fixture work; they are not established by this file.
--
-- All monetary amounts are exact USD cents: NUMERIC(14,2). Compensation
-- base_salary is annual; bonus_target_pct stores percentage points (0..100),
-- not a fraction. Payroll amounts may be negative for corrections/net pay.
-- Numeric NaN is excluded explicitly. There is no header/detail equality
-- constraint: DR-3 requires a deliberate mismatch in the future fixture.
--
-- Temporal assumption: effective ranges are [start, effective_to); NULL ends
-- are open-ended. A compensation employee has at most one open row; an HR
-- principal may have one open assignment per division, across many divisions.
-- Closed-range overlaps are not resolved by this DDL and remain a future
-- fixture invariant. HR policy uses effective_to IS NULL per FR-6.7.
-- Department attribution is current-only; no transfer-history table exists.
-- No business date/timestamp receives a wall-clock default.
--
-- Foreign-key actions are explicit NO ACTION on key changes and RESTRICT on
-- deletion, preserving referenced history. The manager FK is deferrable so
-- a future fixture transaction can explicitly defer insertion ordering.
-- Authorization, grants, RLS and scope functions belong to Prompt 2.

CREATE TABLE public.divisions (
    division_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    division_code TEXT NOT NULL,
    division_name TEXT NOT NULL,
    CONSTRAINT divisions_pk PRIMARY KEY (division_id),
    CONSTRAINT divisions_id_positive CHECK (division_id > 0),
    CONSTRAINT divisions_code_unique UNIQUE (division_code),
    CONSTRAINT divisions_name_unique UNIQUE (division_name),
    CONSTRAINT divisions_code_nonblank CHECK (btrim(division_code) <> ''),
    CONSTRAINT divisions_name_nonblank CHECK (btrim(division_name) <> '')
);

CREATE TABLE public.locations (
    location_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    location_code TEXT NOT NULL,
    location_name TEXT NOT NULL,
    CONSTRAINT locations_pk PRIMARY KEY (location_id),
    CONSTRAINT locations_id_positive CHECK (location_id > 0),
    CONSTRAINT locations_code_unique UNIQUE (location_code),
    CONSTRAINT locations_code_nonblank CHECK (btrim(location_code) <> ''),
    CONSTRAINT locations_name_nonblank CHECK (btrim(location_name) <> '')
);

CREATE TABLE public.departments (
    department_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    division_id INTEGER NOT NULL,
    department_code TEXT NOT NULL,
    department_name TEXT NOT NULL,
    CONSTRAINT departments_pk PRIMARY KEY (department_id),
    CONSTRAINT departments_id_positive CHECK (department_id > 0),
    CONSTRAINT departments_code_unique UNIQUE (department_code),
    CONSTRAINT departments_division_name_unique
        UNIQUE (division_id, department_name),
    CONSTRAINT departments_division_fk FOREIGN KEY (division_id)
        REFERENCES public.divisions (division_id)
        ON UPDATE NO ACTION ON DELETE RESTRICT,
    CONSTRAINT departments_code_nonblank CHECK (btrim(department_code) <> ''),
    CONSTRAINT departments_name_nonblank CHECK (btrim(department_name) <> '')
);

CREATE TABLE public.positions (
    position_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    position_code TEXT NOT NULL,
    position_name TEXT NOT NULL,
    CONSTRAINT positions_pk PRIMARY KEY (position_id),
    CONSTRAINT positions_id_positive CHECK (position_id > 0),
    CONSTRAINT positions_code_unique UNIQUE (position_code),
    CONSTRAINT positions_code_nonblank CHECK (btrim(position_code) <> ''),
    CONSTRAINT positions_name_nonblank CHECK (btrim(position_name) <> '')
);

CREATE TABLE public.employees (
    employee_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    employee_number VARCHAR(6) NOT NULL,
    first_name TEXT NOT NULL,
    last_name TEXT NOT NULL,
    email TEXT NOT NULL,
    department_id INTEGER NOT NULL,
    position_id INTEGER NOT NULL,
    location_id INTEGER NOT NULL,
    manager_id INTEGER,
    hire_date DATE NOT NULL,
    termination_date DATE,
    status TEXT NOT NULL,
    employment_type TEXT NOT NULL,
    legal_entity TEXT NOT NULL,
    CONSTRAINT employees_pk PRIMARY KEY (employee_id),
    CONSTRAINT employees_id_positive CHECK (employee_id > 0),
    CONSTRAINT employees_number_unique UNIQUE (employee_number),
    CONSTRAINT employees_email_unique UNIQUE (email),
    CONSTRAINT employees_number_format CHECK (employee_number ~ '^S[0-9]{5}$'),
    CONSTRAINT employees_first_name_nonblank CHECK (btrim(first_name) <> ''),
    CONSTRAINT employees_last_name_nonblank CHECK (btrim(last_name) <> ''),
    CONSTRAINT employees_email_nonblank CHECK (btrim(email) <> ''),
    CONSTRAINT employees_status_nonblank CHECK (btrim(status) <> ''),
    CONSTRAINT employees_employment_type_nonblank
        CHECK (btrim(employment_type) <> ''),
    CONSTRAINT employees_legal_entity_nonblank CHECK (btrim(legal_entity) <> ''),
    CONSTRAINT employees_not_own_manager CHECK (manager_id <> employee_id),
    -- A cancellation may precede the intended hire date. Other termination
    -- dates must not precede hire. Status/type lists stay open: the FRD gives
    -- canonical filters, not a complete authoritative enumeration.
    CONSTRAINT employees_termination_order CHECK (
        termination_date IS NULL OR termination_date >= hire_date
        OR status = 'cancelled_pre_hire'
    ),
    CONSTRAINT employees_department_fk FOREIGN KEY (department_id)
        REFERENCES public.departments (department_id)
        ON UPDATE NO ACTION ON DELETE RESTRICT,
    CONSTRAINT employees_position_fk FOREIGN KEY (position_id)
        REFERENCES public.positions (position_id)
        ON UPDATE NO ACTION ON DELETE RESTRICT,
    CONSTRAINT employees_location_fk FOREIGN KEY (location_id)
        REFERENCES public.locations (location_id)
        ON UPDATE NO ACTION ON DELETE RESTRICT,
    CONSTRAINT employees_manager_fk FOREIGN KEY (manager_id)
        REFERENCES public.employees (employee_id)
        ON UPDATE NO ACTION ON DELETE RESTRICT
        DEFERRABLE INITIALLY IMMEDIATE
);

CREATE TABLE public.employee_compensation (
    compensation_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    employee_id INTEGER NOT NULL,
    effective_date DATE NOT NULL,
    effective_to DATE,
    base_salary NUMERIC(14,2) NOT NULL,
    bonus_target_pct NUMERIC(5,2) NOT NULL,
    currency_code VARCHAR(3) NOT NULL,
    CONSTRAINT employee_compensation_pk PRIMARY KEY (compensation_id),
    CONSTRAINT employee_compensation_id_positive CHECK (compensation_id > 0),
    CONSTRAINT employee_compensation_start_unique
        UNIQUE (employee_id, effective_date),
    CONSTRAINT employee_compensation_employee_fk FOREIGN KEY (employee_id)
        REFERENCES public.employees (employee_id)
        ON UPDATE NO ACTION ON DELETE RESTRICT,
    CONSTRAINT employee_compensation_date_order
        CHECK (effective_to IS NULL OR effective_to > effective_date),
    CONSTRAINT employee_compensation_salary_valid
        CHECK (base_salary <> 'NaN'::NUMERIC AND base_salary >= 0),
    CONSTRAINT employee_compensation_bonus_valid CHECK (
        bonus_target_pct <> 'NaN'::NUMERIC
        AND bonus_target_pct BETWEEN 0 AND 100
    ),
    CONSTRAINT employee_compensation_usd CHECK (currency_code = 'USD')
);

CREATE TABLE public.payroll_runs (
    payroll_run_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    run_number TEXT NOT NULL,
    pay_period_start DATE NOT NULL,
    pay_period_end DATE NOT NULL,
    pay_date DATE NOT NULL,
    pay_frequency TEXT NOT NULL,
    is_off_cycle BOOLEAN NOT NULL,
    status TEXT NOT NULL,
    currency_code VARCHAR(3) NOT NULL,
    created_by_employee_id INTEGER NOT NULL,
    approved_by_employee_id INTEGER,
    approved_date DATE,
    total_gross_pay NUMERIC(14,2) NOT NULL,
    total_tax NUMERIC(14,2) NOT NULL,
    total_deductions NUMERIC(14,2) NOT NULL,
    total_net_pay NUMERIC(14,2) NOT NULL,
    CONSTRAINT payroll_runs_pk PRIMARY KEY (payroll_run_id),
    CONSTRAINT payroll_runs_id_positive CHECK (payroll_run_id > 0),
    CONSTRAINT payroll_runs_number_unique UNIQUE (run_number),
    CONSTRAINT payroll_runs_number_nonblank CHECK (btrim(run_number) <> ''),
    CONSTRAINT payroll_runs_period_order CHECK (pay_period_end >= pay_period_start),
    CONSTRAINT payroll_runs_biweekly CHECK (pay_frequency = 'biweekly'),
    CONSTRAINT payroll_runs_status_nonblank CHECK (btrim(status) <> ''),
    CONSTRAINT payroll_runs_usd CHECK (currency_code = 'USD'),
    CONSTRAINT payroll_runs_amounts_finite CHECK (
        total_gross_pay <> 'NaN'::NUMERIC AND total_tax <> 'NaN'::NUMERIC
        AND total_deductions <> 'NaN'::NUMERIC AND total_net_pay <> 'NaN'::NUMERIC
    ),
    CONSTRAINT payroll_runs_creator_fk FOREIGN KEY (created_by_employee_id)
        REFERENCES public.employees (employee_id)
        ON UPDATE NO ACTION ON DELETE RESTRICT,
    CONSTRAINT payroll_runs_approver_fk FOREIGN KEY (approved_by_employee_id)
        REFERENCES public.employees (employee_id)
        ON UPDATE NO ACTION ON DELETE RESTRICT
    -- Physical choices: header totals use the names above; total_tax is
    -- included in total_deductions. No arithmetic/header-detail equation is
    -- enforced. status is one field, allowing posted, closed and approved
    -- without inventing a complete enum or a second closed-state flag.
    -- is_off_cycle is independent of the normal biweekly cadence. Period
    -- length and pay-date offsets are not constrained for corrections.
);

CREATE TABLE public.payroll_results (
    payroll_result_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    payroll_run_id INTEGER NOT NULL,
    employee_id INTEGER NOT NULL,
    gross_pay NUMERIC(14,2) NOT NULL,
    tax_amount NUMERIC(14,2) NOT NULL,
    total_deductions NUMERIC(14,2) NOT NULL,
    net_pay NUMERIC(14,2) NOT NULL,
    CONSTRAINT payroll_results_pk PRIMARY KEY (payroll_result_id),
    CONSTRAINT payroll_results_id_positive CHECK (payroll_result_id > 0),
    CONSTRAINT payroll_results_run_employee_unique
        UNIQUE (payroll_run_id, employee_id),
    CONSTRAINT payroll_results_run_fk FOREIGN KEY (payroll_run_id)
        REFERENCES public.payroll_runs (payroll_run_id)
        ON UPDATE NO ACTION ON DELETE RESTRICT,
    CONSTRAINT payroll_results_employee_fk FOREIGN KEY (employee_id)
        REFERENCES public.employees (employee_id)
        ON UPDATE NO ACTION ON DELETE RESTRICT,
    CONSTRAINT payroll_results_amounts_finite CHECK (
        gross_pay <> 'NaN'::NUMERIC AND tax_amount <> 'NaN'::NUMERIC
        AND total_deductions <> 'NaN'::NUMERIC AND net_pay <> 'NaN'::NUMERIC
    )
    -- As at the header, tax_amount is included in total_deductions.
    -- Negative net, zero tax and signed correction amounts are permitted.
);

CREATE TABLE public.payroll_earnings (
    payroll_earning_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    payroll_result_id INTEGER NOT NULL,
