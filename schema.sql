    CONSTRAINT payroll_earnings_type_nonblank CHECK (btrim(earning_type) <> ''),
    CONSTRAINT payroll_earnings_amount_finite CHECK (amount <> 'NaN'::NUMERIC),
    CONSTRAINT payroll_earnings_result_fk FOREIGN KEY (payroll_result_id)
        REFERENCES public.payroll_results (payroll_result_id)
        ON UPDATE NO ACTION ON DELETE RESTRICT
);

